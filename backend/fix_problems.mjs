for (const p of db.problems) {
  let changed = false;

  // 1. Fix short descriptions
  if (descriptionFixes[p.number]) {
    p.description = descriptionFixes[p.number];
    descFixed++;
    changed = true;
  }

  // 2. Fix Interview test cases
  if (p.category === 'Interview' && (!p.testCases || p.testCases.length === 0)) {
    const fix = interviewTestCases[p.number];
    if (fix) {
      p.testCases = fix.testCases;
      if (!p.inputFormat && fix.inputFormat) p.inputFormat = fix.inputFormat;
      if (!p.outputFormat && fix.outputFormat) p.outputFormat = fix.outputFormat;
      if (!p.sampleInput && fix.sampleInput !== undefined) p.sampleInput = fix.sampleInput;
      if (!p.sampleOutput && fix.sampleOutput) p.sampleOutput = fix.sampleOutput;
      if (!p.explanation && fix.explanation) p.explanation = fix.explanation;
      tcAdded++;
      changed = true;
    }
  }

  // 3. Fix C test cases (problems with no test cases)
  if (p.category === 'C' && (!p.testCases || p.testCases.length === 0)) {
    const fix = cTestCases[p.number];
    if (fix) {
      p.testCases = fix.testCases;
      if (!p.inputFormat) p.inputFormat = fix.inputFormat;
      if (!p.outputFormat) p.outputFormat = fix.outputFormat;
      if (p.sampleInput === undefined) p.sampleInput = fix.sampleInput;
      if (!p.sampleOutput) p.sampleOutput = fix.sampleOutput;
      tcAdded++;
      changed = true;
    }
  }

  // 4. Normalize C testCases: change (None) input → empty, and ensure expectedOutput field
  if (p.category === 'C' && p.testCases && p.testCases.length > 0) {
    for (const tc of p.testCases) {
      // Normalize (None) input
      if (tc.input === '(None)' || tc.input === 'None') {
        tc.input = '';
        changed = true;
      }
      // Normalize output → expectedOutput
      if (tc.output !== undefined && tc.expectedOutput === undefined) {
        tc.expectedOutput = tc.output;
        changed = true;
      }
    }
  }

  // 5. Fix missing inputFormat/outputFormat/sampleInput/sampleOutput for C problems
  // by parsing from embedded description
  if (p.category === 'C' && (!p.inputFormat || !p.outputFormat || !p.sampleInput || !p.sampleOutput)) {
    const parsed = parseDescriptionFields(p.description || '');
    
    if (!p.inputFormat && parsed.inputFormat) {
      p.inputFormat = parsed.inputFormat;
      formatAdded++;
      changed = true;
    }
    if (!p.outputFormat && parsed.outputFormat) {
      p.outputFormat = parsed.outputFormat;
      formatAdded++;
      changed = true;
    }
    
    // For sample, use first public test case
    if ((!p.sampleInput || !p.sampleOutput) && p.testCases && p.testCases.length > 0) {
      const firstTC = p.testCases[0];
      if (!p.sampleInput) {
        p.sampleInput = normalizeInput(firstTC.input || '');
        changed = true;
      }
      if (!p.sampleOutput) {
        p.sampleOutput = firstTC.expectedOutput || firstTC.output || '';
        changed = true;
      }
    }

    // Use examples if available
    if (!p.sampleInput && p.examples && p.examples.length > 0) {
      const ex = p.examples[0];
      if (ex.input && ex.input !== 'None.') p.sampleInput = ex.input;
      if (ex.output) p.sampleOutput = ex.output;
      if (ex.explanation) p.explanation = ex.explanation;
      changed = true;
    }
  }

  // 6. Fix missing inputFormat/outputFormat for Interview problems
  if (p.category === 'Interview' && (!p.inputFormat || !p.outputFormat)) {
    const fix = interviewTestCases[p.number];
    if (fix) {
      if (!p.inputFormat && fix.inputFormat) { p.inputFormat = fix.inputFormat; formatAdded++; changed = true; }
      if (!p.outputFormat && fix.outputFormat) { p.outputFormat = fix.outputFormat; formatAdded++; changed = true; }
      if (!p.sampleInput && fix.sampleInput !== undefined) { p.sampleInput = fix.sampleInput; changed = true; }
      if (!p.sampleOutput && fix.sampleOutput) { p.sampleOutput = fix.sampleOutput; changed = true; }
      if (!p.explanation && fix.explanation) { p.explanation = fix.explanation; changed = true; }
    }
    // Try to parse from description (for problems that have embedded format)
    const parsed = parseDescriptionFields(p.description || '');
    if (!p.inputFormat && parsed.inputFormat) { p.inputFormat = parsed.inputFormat; formatAdded++; changed = true; }
    if (!p.outputFormat && parsed.outputFormat) { p.outputFormat = parsed.outputFormat; formatAdded++; changed = true; }
  }

  if (changed) fixedCount++;
}

