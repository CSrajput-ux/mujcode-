function tc(input, expectedOutput, visibility = 'hidden') {
  return { input: String(input), expectedOutput: String(expectedOutput), visibility };
}
function tcPub(input, expectedOutput) { return tc(input, expectedOutput, 'public'); }

// Parse inputFormat and outputFormat from embedded description markdown
function parseDescriptionFields(description = '') {
  const inputMatch = description.match(/\*\*Input Format\*\*\s*\n([\s\S]*?)(?=\n\*\*Output Format\*\*|\n\*\*Constraints\*\*|$)/i);
  const outputMatch = description.match(/\*\*Output Format\*\*\s*\n([\s\S]*?)(?=\n\*\*Constraints\*\*|\n\*\*Input Format\*\*|$)/i);
  return {
    inputFormat: inputMatch ? inputMatch[1].trim().replace(/^- /, '') : null,
    outputFormat: outputMatch ? outputMatch[1].trim().replace(/^- /, '') : null,
  };
}

// Normalize (None) inputs for C problems
function normalizeInput(input) {
  if (!input || input === '(None)' || input === 'None' || input.trim() === '') return '';
  return input;
}

